"""Reconciliation break detection: generate data, evaluate, and show a day's ranked queue."""

from __future__ import annotations

import argparse
import json
from dataclasses import replace
from pathlib import Path

import pandas as pd

from . import drift as D
from . import generate as G
from . import plots
from .evaluate import CAPACITY, TRAIN_DAYS, analyst_queue, evaluate, typical_day
from .explain import LLMExplainer, anthropic_provider
from .io import Dataset, from_generated, load

DEFAULT_SEED = 7
ROBUSTNESS_SEEDS = (7, 1, 2, 3, 4)


def _md_table(df: pd.DataFrame) -> str:
    cells = [[str(c) for c in df.columns]] + [
        [str(v) for v in r] for r in df.itertuples(index=False)
    ]
    out = ["| " + " | ".join(cells[0]) + " |", "|" + "---|" * len(df.columns)]
    out += ["| " + " | ".join(r) + " |" for r in cells[1:]]
    return "\n".join(out)


def _write_results(ds: Dataset, out: Path, train_days: int, capacity: int) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    fig_dir = out / "figures"
    fig_dir.mkdir(exist_ok=True)

    r = evaluate(ds, train_days=train_days, capacity=capacity)
    (out / "metrics.json").write_text(json.dumps(r.metrics, indent=2, default=str))
    r.daily.to_csv(out / "triage_by_day.csv", index=False)
    r.alerts.to_csv(out / "surveillance_alerts.csv", index=False)

    plots.value_recall_curve(r.curves, capacity, fig_dir / "value_cleared_by_k.png")
    plots.precision_vs_value(r.metrics["triage"]["strategies"], fig_dir / "hit_rate_vs_value.png")
    plots.daily_exceptions(
        r.exceptions,
        ds.meta["trade_days"],
        r.metrics["triage"]["split_date"],
        r.alerts,
        fig_dir / "daily_exceptions.png",
    )

    day = typical_day(r.daily)
    vr = r.daily.set_index(["date", "strategy"])["value_recall_at_k"]
    q = analyst_queue(r.exceptions, day, capacity)
    q.to_csv(out / "sample_queue.csv", index=False)
    shown = q.assign(
        exposure_usd=q["exposure_usd"].map(lambda v: f"{v:,.0f}"),
        p_needs_action=q["p_needs_action"].map(lambda v: f"{v:.2f}"),
        needs_action=q["needs_action"].map({True: "yes", False: "no"}),
    )
    shown = shown[
        ["rank", "break_type", "exposure_usd", "p_needs_action", "needs_action", "reason"]
    ]
    shown.columns = ["Rank", "Break", "Exposure (USD)", "P(real)", "Actually real", "Reason"]
    (out / "sample_queue.md").write_text(
        f"# Analyst queue for {day} (held-out day, top {capacity})\n\n"
        "A typical day: the one where the model's share of at-risk value cleared in the "
        f"first {capacity} items ({vr[(day, 'model')]:.0%}) is closest to its median over "
        f"the held-out days. Desk rules cleared {vr[(day, 'desk_rules')]:.0%} that day.\n\n"
        "Generated by `recon demo`. 'Actually real' is ground truth from the synthetic "
        "generator and is not available to the model.\n\n" + _md_table(shown) + "\n"
    )
    return r.metrics


def _robustness(out: Path, seeds, train_days: int, capacity: int) -> pd.DataFrame:
    rows = []
    for seed in seeds:
        ds = from_generated(G.generate(replace(G.GeneratorConfig(), seed=seed)))
        m = evaluate(ds, train_days=train_days, capacity=capacity, n_boot=200).metrics
        strat = m["triage"]["strategies"]
        rows.append(
            {
                "seed": seed,
                "pair_precision": round(m["matching"]["pair_precision"], 4),
                "break_type_accuracy": round(m["matching"]["break_type_accuracy"], 4),
                "missing_only_auc": round(m["model"]["missing_only_roc_auc"], 3),
                **{
                    f"value@{capacity}_{k}": round(v["value_recall_at_k"]["mean"], 3)
                    for k, v in strat.items()
                    if "value_recall_at_k" in v
                },
                "incidents_detected": sum(i["detected"] for i in m["surveillance"]["incidents"]),
                "false_alerts": m["surveillance"]["false_alerts"],
            }
        )
    df = pd.DataFrame(rows)
    df.to_csv(out / "robustness_by_seed.csv", index=False)
    return df


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="recon", description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)

    g = sub.add_parser("generate", help="write a synthetic dataset")
    g.add_argument("--out", default="data")
    g.add_argument("--seed", type=int, default=DEFAULT_SEED)
    g.add_argument("--days", type=int, default=120)

    e = sub.add_parser("evaluate", help="reconcile, triage and evaluate a dataset")
    e.add_argument("--data", default="data")
    e.add_argument("--out", default="results")
    e.add_argument("--train-days", type=int, default=TRAIN_DAYS)
    e.add_argument("--capacity", type=int, default=CAPACITY)

    q = sub.add_parser("queue", help="print one day's ranked queue with reasons")
    q.add_argument("--data", default="data")
    q.add_argument("--date", help="business day, YYYY-MM-DD (default: a held-out day)")
    q.add_argument("--capacity", type=int, default=CAPACITY)
    q.add_argument("--llm", action="store_true", help="reword reasons with the Anthropic API")

    d = sub.add_parser("demo", help="generate, evaluate and check robustness in one go")
    d.add_argument("--out", default="results")
    d.add_argument("--data", default="data")
    d.add_argument("--skip-robustness", action="store_true")

    dr = sub.add_parser("drift", help="compare model and rules when counterparties drift")
    dr.add_argument("--out", default="results/drift")
    dr.add_argument("--seeds", type=int, nargs="+", default=list(ROBUSTNESS_SEEDS))

    args = ap.parse_args(argv)

    if args.cmd == "generate":
        cfg = replace(G.GeneratorConfig(), seed=args.seed, n_days=args.days)
        path = G.write(G.generate(cfg), args.out)
        print(f"wrote synthetic dataset to {path}/")

    elif args.cmd == "evaluate":
        m = _write_results(load(args.data), Path(args.out), args.train_days, args.capacity)
        print(json.dumps(m["triage"]["strategies"]["model"], indent=2))

    elif args.cmd == "queue":
        ds = load(args.data)
        r = evaluate(ds, n_boot=50)
        day = args.date or typical_day(r.daily)
        queue = analyst_queue(r.exceptions, day, args.capacity)
        explainer = LLMExplainer(anthropic_provider()) if args.llm else None
        rows = r.exceptions.set_index("exception_id")
        for item in queue.itertuples():
            reason = item.reason
            if explainer is not None:
                ex = explainer.explain(
                    rows.loc[item.exception_id].to_dict() | {"exception_id": item.exception_id}
                )
                reason = f"[{ex.source}] {ex.text}"
            print(
                f"{item.rank:>2}. {item.break_type:<19} USD {item.exposure_usd:>12,.0f}  "
                f"P(real)={item.p_needs_action:.2f}\n    {reason}"
            )

    elif args.cmd == "demo":
        data = G.generate(replace(G.GeneratorConfig(), seed=DEFAULT_SEED))
        G.write(data, args.data)
        out = Path(args.out)
        m = _write_results(from_generated(data), out, TRAIN_DAYS, CAPACITY)
        s = m["triage"]["strategies"]
        print(
            f"value cleared in first {CAPACITY}: "
            + ", ".join(
                f"{name} {s[name]['value_recall_at_k']['mean']:.0%}"
                for name in ("model", "counterparty_rule", "largest_exposure", "desk_rules")
            )
        )
        if not args.skip_robustness:
            print(_md_table(_robustness(out, ROBUSTNESS_SEEDS, TRAIN_DAYS, CAPACITY)))
        print(f"results written to {out}/")

    elif args.cmd == "drift":
        out = Path(args.out)
        out.mkdir(parents=True, exist_ok=True)
        m, tables = D.run(args.seeds)
        for stale in out.glob("seed_*.csv"):  # keep the folder to one run's seeds
            stale.unlink()
        (out / "metrics.json").write_text(json.dumps(m, indent=2))
        for seed, t in tables.items():
            t.round(6).to_csv(out / f"seed_{seed}.csv", index=False)
        plots.drift_comparison(m["pooled"], len(args.seeds), out / "drift_value_cleared.png")
        rows = []
        for scenario, entry in m["pooled"].items():
            for period in D.PERIODS:
                v = entry[period]["value_recall_at_k"]
                rows.append(
                    {"scenario": scenario, "period": period}
                    | {k: f"{x['mean']:.1%}" for k, x in v.items()}
                )
        print(_md_table(pd.DataFrame(rows)))
        print(f"results written to {out}/")


if __name__ == "__main__":
    main()
